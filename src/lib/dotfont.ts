export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function glyph(ch: string): string[] {
  return G[ch.toUpperCase()] ?? G[" "];
}

export type Dot = { x: number; y: number; on: boolean };

/**
 * Lays a string out on the grid. `gap` is the number of empty columns
 * between characters. Returns every cell, lit or not, so callers can
 * draw an unpowered matrix behind the lit dots.
 */
export function layout(text: string, gap = 1): { dots: Dot[]; cols: number } {
  const dots: Dot[] = [];
  const chars = [...text];
  chars.forEach((ch, i) => {
    const g = glyph(ch);
    const ox = i * (GLYPH_W + gap);
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) {
        dots.push({ x: ox + x, y, on: g[y][x] === "#" });
      }
    }
  });
  const cols = chars.length === 0 ? 0 : chars.length * (GLYPH_W + gap) - gap;
  return { dots, cols };
}
